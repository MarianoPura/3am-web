                [$order, $equipment, $name . ' Camera', $orderDate, $orderDate]);
            foreach (['service_payment_form' => ['A', 'unpaid', null, null],
                'service_admin_payment_review' => ['B', 'pending', $method, $serviceProof]] as $key => [$suffix, $paymentStatus, $paymentMethod, $proof]) {
                $insert($key,
                    "INSERT INTO rental_service_requests(reference,submission_key,user_id,rental_item_id,service_name,customer_name,customer_email,customer_phone,event_start_date,event_end_date,location,details,status,customer_message,reviewed_by,reviewed_at,notification_attempted_at,quote_amount,quote_notes,quote_version,payment_method_id,payment_reference,payment_proof_path,payment_status) VALUES(?,?,?,?,?,?,?,?,?,?,?,?,'approved',?,?,CURRENT_TIMESTAMP,CURRENT_TIMESTAMP,1500,?,1,?,?,?,?)",
                    ['BROWSER-' . strtoupper($state['key']) . '-' . $suffix, bin2hex(random_bytes(32)), $state['ids']['customer'],
                        $service, $name . ' Production crew', $name . ' Customer', $accounts['customer']['email'], '0000000000',
                        $orderDate, $orderDate, 'Fictional QA venue', 'Fictional service requirements for local layout review.',
                        'Approved for fictional layout testing only.', $state['ids']['admin'], 'Fictional local quotation, no real payment requested.',
                        $paymentMethod, $paymentStatus === 'pending' ? 'FICTIONAL-SERVICE-PAYMENT' : null, $proof, $paymentStatus]);
            }
            $routes = [
                'equipment_catalogue' => '/rentals/items?type=equipment&category=' . $slug . '-equipment',
                'services_catalogue' => '/rentals/items?type=services&category=' . $slug . '-services',
                'customer_orders' => '/rentals/orders',
                'customer_order_status' => '/rentals/order-status/' . $statusToken,
                'customer_receipt' => '/rentals/confirmation/' . $statusToken,
                'customer_equipment_proof' => '/rentals/orders/' . $order . '/proof',
                'customer_service_payment' => '/rentals/service-requests/' . $state['ids']['service_payment_form'],
                'customer_service_payment_review' => '/rentals/service-requests/' . $state['ids']['service_admin_payment_review'],
                'customer_service_proof' => '/rentals/service-requests/' . $state['ids']['service_admin_payment_review'] . '/proof',
                'customer_service_request_form' => '/rentals/services/' . $service . '/request',
                'admin_equipment_order' => '/rentals/admin/orders/' . $order,
                'admin_equipment_proof' => '/rentals/admin/proof/' . $order,
                'admin_service_review' => '/rentals/admin/service-requests/' . $state['ids']['service_admin_payment_review'],
                'admin_service_proof' => '/rentals/service-requests/' . $state['ids']['service_admin_payment_review'] . '/proof',
                'admin_item_edit' => '/rentals/admin/items/' . $equipment . '/edit',
                'admin_category_edit' => '/rentals/admin/categories/' . $equipmentCategory . '/edit',
                'admin_payment_edit' => '/rentals/admin/payments/' . $method . '/edit',
                'cart' => '/rentals/cart', 'checkout' => '/rentals/checkout',
            ];
            foreach ($routes as $key => $path) { $state['routes'][$key] = url($path); }
            browserFixtureWrite($accountsPath, 'admin: ' . $accounts['admin']['email'] . "\nPassword: " . $accounts['admin']['password']
                . "\n\ncustomer: " . $accounts['customer']['email'] . "\nPassword: " . $accounts['customer']['password'] . "\n", true);
            unset($accounts, $password, $statusToken);
            $state['ready'] = true;
            browserFixtureSave($statePath, $state);
            $db->commit();
            $prepared = true;
            echo "Prepared: 2 fictional accounts, 2 categories/items, 1 manual method, 1 filled Cart, 1 Pending Equipment order, 2 quoted Service requests, 2 encrypted proofs and 2 gallery images.\n";
            echo "Private files: storage/tmp/browser-fixture-accounts.txt and storage/tmp/browser-fixture-state.json.\n";
            echo "Temporary browser fixtures retained until --cleanup; no email, DDL, existing records or environment changes.\n";
        } catch (Throwable $error) {
            if ($db->inTransaction()) { $db->rollBack(); }
            throw $error;
        }
    } finally {
        try {
            if ($argv[1] === '--prepare' && !$prepared && is_array($state)) {
                if ($db->inTransaction()) { $db->rollBack(); }
                browserFixtureCleanup($db, $state, $statePath, $accountsPath);
                echo "Failed preparation cleanup: owned rows/files removed; no browser fixtures retained.\n";
            }
        } finally { $db->selectValue('SELECT RELEASE_LOCK(?)', ['3am-home-browser-fixtures']); }
    }
}

try {
    browserFixtureMain($argv);
} catch (Throwable $error) {
    // Do not emit a trace, bindings, credentials, keys or private routes.
    $safe = $error instanceof RuntimeException && $error->getPrevious() === null ? $error->getMessage() : 'Local fixture operation failed; inspect ownership state privately before retrying.';
    fwrite(STDERR, "STOP: " . $safe . "\n");
    exit(1);
}
