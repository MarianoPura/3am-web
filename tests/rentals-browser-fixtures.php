            $cart = $insert('cart', 'INSERT INTO carts(user_id) VALUES(?)', [$state['ids']['customer']]);
            $cartDate = (new DateTimeImmutable('today'))->modify('+10 days')->format('Y-m-d');
            $insert('cart_item', 'INSERT INTO cart_items(cart_id,rental_item_id,quantity,rental_start_date,rental_end_date) VALUES(?,?,1,?,?)',
                [$cart, $equipment, $cartDate, $cartDate]);
            $orderDate = (new DateTimeImmutable('today'))->modify('+20 days')->format('Y-m-d');
            $statusToken = bin2hex(random_bytes(32));
            $order = $insert('equipment_order',
                'INSERT INTO order_header(order_number,user_id,customer_name,customer_email,customer_phone,payment_method_id,payment_reference,subtotal,security_deposit,total_amount,notes,payment_proof_path,status_token,payment_status) VALUES(?,?,?,?,?,?,?,100,25,125,?,?,?,0)',
